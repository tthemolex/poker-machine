#!/usr/bin/env python3
"""Envelope check of the full assembly (every printed + vendor part + cards).

Measures, from the exported meshes, the bounding box and the maximum radius from the
turret axis at turret angles 0..315 deg (step 45) and both rack extremes. Turret and rack
parts are rotated in Python (the base is static), so the footprint is the true swept one.
PASS iff footprint diameter <= ENV_MAX_D and height <= ENV_MAX_H.
Writes cad/size_report.json and renders/size_report.md (for README).
"""
import json
import sys

import numpy as np

sys.path.insert(0, str(__import__("pathlib").Path(__file__).resolve().parent))
from cad_common import CAD, ROOT, assembly_parts, export_placed, load_mesh, params, table  # noqa: E402

ANGLES = list(range(0, 360, 45))


def rotz(v, deg):
    a = np.radians(deg)
    c, s = np.cos(a), np.sin(a)
    return v @ np.array([[c, s, 0], [-s, c, 0], [0, 0, 1]])


def main():
    P = params()
    parts = assembly_parts()
    group = dict(parts)
    names = [n for n, _ in parts]
    rows, worst = [], dict(d=0, h=0)
    per_part = {}
    for pos in (0.0, P["RACK_TRAVEL"]):
        paths = export_placed(names, pos, 0)
        verts = {n: load_mesh(p).vertices for n, p in paths.items() if p is not None}
        for n, v in verts.items():
            r = float(np.hypot(v[:, 0], v[:, 1]).max())
            per_part[n] = (max(per_part.get(n, (0, 0))[0], r), max(per_part.get(n, (0, 0))[1], float(v[:, 2].max())))
        for ang in ANGLES:
            allv = np.vstack([rotz(v, ang) if group[n] != "base" else v for n, v in verts.items()])
            lo, hi = allv.min(0), allv.max(0)
            rmax = float(np.hypot(allv[:, 0], allv[:, 1]).max())
            h = float(hi[2] - min(lo[2], 0.0))
            rows.append([f"{pos:g}", ang, f"{hi[0] - lo[0]:.1f}", f"{hi[1] - lo[1]:.1f}", f"{h:.1f}", f"{rmax:.2f}", f"{2 * rmax:.1f}"])
            worst["d"] = max(worst["d"], 2 * rmax)
            worst["h"] = max(worst["h"], h)
            if worst.get("bx", 0) < max(hi[0] - lo[0], hi[1] - lo[1]):
                worst["bx"] = float(max(hi[0] - lo[0], hi[1] - lo[1]))
    print(table(rows, ["rack_pos", "turret deg", "bbox X", "bbox Y", "height", "max r", "footprint D"]))
    D, H = worst["d"], worst["h"]
    okD, okH = D <= P["ENV_MAX_D"], H <= P["ENV_MAX_H"]
    top_r = sorted(per_part.items(), key=lambda kv: -kv[1][0])[:8]
    top_z = sorted(per_part.items(), key=lambda kv: -kv[1][1])[:6]
    print("\nlargest radius from the turret axis (envelope drivers):")
    print(table([[n, group[n], f"{r:.2f}"] for n, (r, _) in top_r], ["part", "group", "max r mm"]))
    print("\nhighest parts:")
    print(table([[n, group[n], f"{z:.2f}"] for n, (_, z) in top_z], ["part", "group", "max z mm"]))
    res = dict(footprint_d=round(D, 2), max_radius=round(D / 2, 2), height=round(H, 2), max_bbox_xy=round(worst["bx"], 2),
               limit_d=P["ENV_MAX_D"], limit_h=P["ENV_MAX_H"], stretch_d=P["ENV_STRETCH_D"], stretch_h=P["ENV_STRETCH_H"],
               gap_to_stretch_d=round(D - P["ENV_STRETCH_D"], 2), gap_to_stretch_h=round(H - P["ENV_STRETCH_H"], 2),
               margin_d=round(P["ENV_MAX_D"] - D, 2), margin_h=round(P["ENV_MAX_H"] - H, 2),
               pass_hard=bool(okD and okH), angles=ANGLES, rack_positions=[0, P["RACK_TRAVEL"]],
               drivers_radius=[[n, round(r, 2)] for n, (r, _) in top_r], drivers_height=[[n, round(z, 2)] for n, (_, z) in top_z])
    (CAD / "size_report.json").write_text(json.dumps(res, indent=2) + "\n")
    md = f"""# Size report (generated by tools/cad_size.py)

Measured from the meshes of every placed part (printed, vendor, cards) at turret angles
{ANGLES[0]}..{ANGLES[-1]} deg (step 45) and rack at 0 and {P['RACK_TRAVEL']:g} mm.

| | measured | hard limit | margin | stretch target | gap to stretch |
|---|---|---|---|---|---|
| footprint (2 x max radius) | **{D:.1f} mm** | {P['ENV_MAX_D']:g} mm | {P['ENV_MAX_D'] - D:+.1f} mm | {P['ENV_STRETCH_D']:g} mm | {D - P['ENV_STRETCH_D']:+.1f} mm |
| height | **{H:.1f} mm** | {P['ENV_MAX_H']:g} mm | {P['ENV_MAX_H'] - H:+.1f} mm | {P['ENV_STRETCH_H']:g} mm | {H - P['ENV_STRETCH_H']:+.1f} mm |

Hard limits: **{'PASS' if okD and okH else 'FAIL'}**. Max axis-aligned bounding box side: {worst['bx']:.1f} mm.

Radius drivers: {', '.join(f'{n} {r:.1f}' for n, (r, _) in top_r[:5])}.
Height drivers: {', '.join(f'{n} {z:.1f}' for n, (_, z) in top_z[:4])}.
"""
    (ROOT / "renders").mkdir(exist_ok=True)
    (ROOT / "renders" / "size_report.md").write_text(md)
    print(f"\nfootprint D = {D:.2f} mm (limit {P['ENV_MAX_D']:g}: {'PASS' if okD else 'FAIL'}), "
          f"height = {H:.2f} mm (limit {P['ENV_MAX_H']:g}: {'PASS' if okH else 'FAIL'})")
    print(f"gap to stretch target: D {D - P['ENV_STRETCH_D']:+.1f} mm, H {H - P['ENV_STRETCH_H']:+.1f} mm")
    print("wrote cad/size_report.json, renders/size_report.md")
    sys.exit(0 if okD and okH else 1)


if __name__ == "__main__":
    main()
