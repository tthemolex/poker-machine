#!/usr/bin/env python3
"""Generate firmware/include/geometry.h from the @shared lines of cad/params.scad.

params.scad is the single source of truth for every dimension/ratio the firmware
uses. Usage:  python3 tools/gen_geometry.py [--check]
--check exits 1 if the header on disk differs from what would be generated.
"""
import math
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SCAD = ROOT / "cad" / "params.scad"
HDR = ROOT / "firmware" / "include" / "geometry.h"

LINE = re.compile(r"^\s*([A-Z][A-Z0-9_]*)\s*=\s*(.+?);\s*//\s*@shared\b(.*)$")


def parse(text):
    env = {}
    out = []
    for raw in text.splitlines():
        m = LINE.match(raw)
        if not m:
            continue
        name, expr, comment = m.group(1), m.group(2), m.group(3).strip()
        val = eval(expr, {"__builtins__": {}, "floor": math.floor, "ceil": math.ceil}, env)
        env[name] = val
        out.append((name, val, comment))
    return out


def render(items):
    lines = [
        "// AUTO-GENERATED by tools/gen_geometry.py from cad/params.scad. DO NOT EDIT.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "namespace geom {",
    ]
    for name, val, comment in items:
        c = f"  // {comment}" if comment else ""
        if isinstance(val, int) or (isinstance(val, float) and val.is_integer() and "." not in repr(val) ):
            lines.append(f"constexpr int32_t {name} = {int(val)};{c}")
        else:
            lines.append(f"constexpr float {name} = {float(val)!r}f;{c}")
    lines += ["}  // namespace geom", ""]
    return "\n".join(lines)


def main():
    items = parse(SCAD.read_text())
    text = render(items)
    if "--check" in sys.argv:
        if not HDR.exists() or HDR.read_text() != text:
            print("geometry.h is stale: run python3 tools/gen_geometry.py", file=sys.stderr)
            sys.exit(1)
        print(f"geometry.h up to date ({len(items)} values)")
        return
    HDR.parent.mkdir(parents=True, exist_ok=True)
    HDR.write_text(text)
    print(f"wrote {HDR.relative_to(ROOT)} ({len(items)} values)")


if __name__ == "__main__":
    main()
